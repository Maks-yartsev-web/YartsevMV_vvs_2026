    print('Найдем позицию первого вхождения "круто" (метод find()):', t.find('круто'))
    print('Заменим "круто" на символ "!" (метод replace()):', t.replace('круто', '!'))
    print('Посчитаем все буквы "о" (метод count()):', t.count('о'))
    print('', 'Введите номер метода, который хотите реализовать:', sep="\n")
    try:
        v = int(input())
        if v not in (1, 2, 3):
            print('Данные некорректны!')
        else:
            if v == 1:
                s = input('Введите исходную строку: ')
                s0 = input('Введите искомую подстроку: ')
                print('Результат:', s.find(s0))
            elif v == 2:
                s = input('Введите исходную строку: ')
                s0 = input('Введите подстроку, которую нужно заменить: ')
                s1 = input('Введите подстроку, НА которую нужно заменить: ')
                k = int(input('Введите кол-во замен (если нужно все, напишите "-1"): '))
                if k < -1:
                    print('Данные некорректны!')
                elif k == -1:
                    print('Результат:', s.replace(s0, s1))
                else:
                    print('Результат:', s.replace(s0, s1, k))
            else:
                s = input('Введите исходную строку: ')
                s0 = input('Введите искомую подстроку: ')
                print('Результат:', s.count(s0))
    except ValueError:
        print('Данные некорректны!')


