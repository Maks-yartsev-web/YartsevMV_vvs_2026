def fix(text):
    # Объединил strip и capitalize в одну строку
    s = text.strip().capitalize()
    
    # Цепочка замен осталась, но работает с переменной s
    s = s.replace('. ', '.').replace('.', '. ')
    s = s.replace(', ', ',').replace(',', ', ')
    s = s.replace(': ', ':').replace(':', ': ')
    s = s.replace('; ', ';').replace(';', '; ')
    s = s.replace('! ', '!').replace('!', '! ')
    s = s.replace('? ', '?').replace('?', '? ')
    s = s.strip()
    
    while '  ' in s:
        s = s.replace('  ', ' ')
        
    out = []
    # Переименовал i в idx и w в s
    for idx in range(len(s)):
        if idx >= 2 and s[idx-2] in '.!?' and s[idx-1] == ' ':
            out.append(s[idx].upper())
        elif idx < len(s)-1 and s[idx] == ' ' and s[idx+1] in '.!?;:,':
            pass
        else:
            out.append(s[idx])
            
    return ''.join(out)


